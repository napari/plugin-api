#!/usr/bin/env python3
"""Build the static site that serves the npe2api v1 API.

Every URL the API answers today becomes a plain file in ``site/``, so any
static host can serve it without running code:

- ``public/<path>`` is copied to ``site/<path>`` (the old Next.js host served
  ``public/`` at the root, so ``/extended_summary.json`` and
  ``/conda/<name>.json`` keep working).
- The ``/api/...`` routes are written without a ``.json`` extension:
  ``api/plugins``, ``api/extended_summary``, ``api/conda-map``,
  ``api/readers``, ``api/manifest/<name>``, ``api/pypi/<name>``,
  ``api/conda/<name>``, and one ``api/shields/<name>`` badge per plugin.
- ``_headers`` sets JSON content types, CORS and the deprecation headers of
  ``/api/conda``. Cloudflare reads it; other hosts ignore it.
- ``index.html`` is the human-readable landing page.

One route cannot be a file: ``/api/conda`` (the conda map) shares its path
with the ``api/conda/`` directory. The Cloudflare Worker in ``worker/``
answers it, together with any request whose slug is not already normalized.
"""

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).parent.parent

# Files in public/ that are also served under /api/<route>.
API_ALIASES = {
    "index.json": "plugins",
    "extended_summary.json": "extended_summary",
    "conda.json": "conda-map",
    "readers.json": "readers",
}

# Per-plugin folders in public/ that are also served under /api/<folder>/<name>.
API_FOLDERS = ("manifest", "pypi", "conda")

SHIELD_LOGO_SVG = (ROOT / "scripts" / "napari_logo.svg").read_text().strip()

# Rules that match the same path are merged, so CORS is set once, for all.
HEADERS = """\
/*
  Access-Control-Allow-Origin: *
/api/*
  Content-Type: application/json; charset=utf-8
"""


def normalize_name(name: str) -> str:
    """Normalize a package name the way the API routes always have (PEP 503)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def shield(message: str | None) -> dict:
    """Return the shields.io endpoint schema for a plugin badge.

    ``message`` is the plugin name as requested, or None if it is unknown.
    """
    return {
        "color": "#0074B8" if message else "#82001A",
        "label": "napari hub",
        "logoSvg": SHIELD_LOGO_SVG,
        "message": message or "unavailable",
        "schemaVersion": 1,
        "style": "flat-square",
    }


def build_site(public_dir: Path, site_dir: Path) -> int:
    """Write the static site from ``public_dir`` into ``site_dir``.

    Returns the number of files written.
    """
    if site_dir.exists():
        shutil.rmtree(site_dir)
    api_dir = site_dir / "api"
    api_dir.mkdir(parents=True)
    count = 0

    def write(dest: Path, source: Path | None = None, text: str | None = None):
        nonlocal count
        dest.parent.mkdir(parents=True, exist_ok=True)
        if source is not None:
            shutil.copyfile(source, dest)
        else:
            dest.write_text(text, encoding="utf-8")
        count += 1

    for source in sorted(public_dir.rglob("*.json")):
        rel = source.relative_to(public_dir)
        write(site_dir / rel, source)
        if len(rel.parts) == 1 and rel.name in API_ALIASES:
            write(api_dir / API_ALIASES[rel.name], source)
        elif len(rel.parts) == 2 and rel.parts[0] in API_FOLDERS:
            write(api_dir / rel.parts[0] / rel.stem, source)

    index = json.loads((public_dir / "index.json").read_text())
    for name in index:
        slug = normalize_name(name)
        write(api_dir / "shields" / slug, text=json.dumps(shield(slug)))
    # The Worker serves this badge for unknown plugins. A leading underscore
    # cannot clash with a plugin, since package names start alphanumeric.
    write(api_dir / "shields" / "_unavailable", text=json.dumps(shield(None)))

    write(site_dir / "_headers", text=HEADERS)
    write(site_dir / "index.html", text=index_html(index))
    return count


def index_html(index: dict[str, str]) -> str:
    """Return the landing page, which lists every plugin manifest."""
    items = "\n".join(
        f'      <li><a href="api/manifest/{name}">{name}-{version}</a></li>'
        for name, version in sorted(index.items())
    )
    # Links are relative so the page also works under a subpath (GitHub Pages).
    return f"""<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>napari plugins</title>
  </head>
  <body>
    <h1>napari plugins</h1>
    <p>This page serves the REST API for napari plugins.</p>
    <p>It is generated by the source code in the
      <a href="https://github.com/napari/npe2api">npe2api repo</a>.</p>
    <p>A user-friendly site for napari plugin information is
      <a href="https://napari-hub.org/">napari-hub.org</a>.</p>
    <h3>Commonly used API endpoints</h3>
    <p>Plugin index: <a href="api/plugins">api/plugins</a></p>
    <p>Summary info: <a href="api/extended_summary">api/extended_summary</a></p>
    <p>PyPI information: use <code>api/pypi/pypi_plugin_name</code> for one
      plugin.</p>
    <p>Conda index: <a href="api/conda-map">api/conda-map</a>
      (see conda info for each plugin at <code>api/conda/pypi_name</code>)</p>
    <p>Fetch errors: <a href="errors.json">errors.json</a></p>
    <h3>Plugin manifests</h3>
    <ul>
{items}
    </ul>
  </body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--public", type=Path, default=ROOT / "public")
    parser.add_argument("--out", type=Path, default=ROOT / "site")
    args = parser.parse_args()
    count = build_site(args.public, args.out)
    print(f"Wrote {count} files to {args.out}")


if __name__ == "__main__":
    main()
